// Declared Node generator for the Space field-kernel metadata (plan B08), the tracing metadata (plan B10)
// and the appearance metadata (plan B11). Writes src/space/render/webgpu/kernel-hashes.js, tracing-hashes.js
// and appearance-hashes.js: the SHA-256 of each WGSL source on disk and of each
// assembled module exactly as the backend executes it (shaders.js shaderCode: wgslConstants() + '\n'
// + the sources joined by '\n'). `--check` fails when the committed metadata is stale. The static
// build copies the metadata unchanged; kernel-metadata.test.js verifies it against the sources.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { shaderCode } from '../src/space/render/webgpu/shaders.js';

const root = new URL('../src/space/render/webgpu/', import.meta.url);
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const load = async id => readFileSync(new URL(`shaders/${id}.wgsl`, root), 'utf8');
// B10: every tracing descriptor is fields + a Menger adapter + the trace core + one entry source.
const TRACING_ASSEMBLIES = ['menger-absent', 'menger-sample'].flatMap(adapter => ['trace-band', 'normals', 'trace-rays'].map(entry => ['fields', adapter, 'trace', entry]));
// B11: shade.wgsl follows fields, a Menger adapter and the trace core; accumulate and display stand alone.
const APPEARANCE_ASSEMBLIES = [...['menger-absent', 'menger-sample'].map(adapter => ['fields', adapter, 'trace', 'shade']), ['accumulate'], ['display'], ['draft-summary'], ['present-draft']];
const TARGETS = [
  { file: 'kernel-hashes.js', name: 'KERNEL_HASHES', sources: ['fields', 'points'], assemblies: [['fields', 'points']] },
  { file: 'tracing-hashes.js', name: 'TRACING_HASHES', sources: ['trace', 'trace-band', 'normals', 'trace-rays', 'menger-sample', 'menger-absent'], assemblies: TRACING_ASSEMBLIES },
  { file: 'appearance-hashes.js', name: 'APPEARANCE_HASHES', sources: ['shade', 'accumulate', 'display', 'draft-summary', 'present-draft'], assemblies: APPEARANCE_ASSEMBLIES },
];

let stale = false;
for (const { file, name, sources: ids, assemblies } of TARGETS) {
  const target = new URL(file, root);
  const sources = Object.fromEntries(ids.map(id => [id, sha256(readFileSync(new URL(`shaders/${id}.wgsl`, root)))]));
  const assembled = {};
  for (const list of assemblies) assembled[list.join('+')] = sha256(await shaderCode(list, load));
  const text = `// GENERATED by scripts/shader-metadata.mjs — do not edit. SHA-256 of each WGSL source and of each
// assembled module (wgslConstants() + '\\n' + sources joined by '\\n'), as the backend executes it.
export const ${name} = Object.freeze({
  sources: Object.freeze(${JSON.stringify(sources, null, 2).replace(/\n/g, '\n  ')}),
  assembled: Object.freeze(${JSON.stringify(assembled, null, 2).replace(/\n/g, '\n  ')}),
});
`;
  let current = null;
  try { current = readFileSync(target, 'utf8'); } catch { /* first generation */ }
  if (process.argv.includes('--check')) {
    if (current !== text) { console.error(`${file} is stale: run node scripts/shader-metadata.mjs`); stale = true; }
    else console.log(`${file} is current`);
  } else if (current !== text) { writeFileSync(target, text); console.log(`wrote ${target.pathname}`); }
  else console.log(`${file} unchanged`);
}
if (stale) process.exit(1);
